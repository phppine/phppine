package org.example.animalsheltersecurity.service;

import lombok.RequiredArgsConstructor;
import org.example.animalsheltersecurity.exception.ResourceNotFoundException;
import org.example.animalsheltersecurity.model.AdoptionApplication;
import org.example.animalsheltersecurity.model.AnimalHandoverRecord;
import org.example.animalsheltersecurity.repository.AdoptionApplicationRepository;
import org.example.animalsheltersecurity.repository.AnimalHandoverRecordRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.util.StringUtils;

import java.time.LocalDateTime;
import java.util.List;

@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class AnimalHandoverRecordService {

    private static final String DEFAULT_STATUS = "PREPARED";
    private static final String CONFIRMED_STATUS = "CONFIRMED";

    private final AnimalHandoverRecordRepository handoverRecordRepository;
    private final AdoptionApplicationRepository adoptionApplicationRepository;

    public List<AnimalHandoverRecord> findAll() {
        return handoverRecordRepository.findAll();
    }

    public AnimalHandoverRecord findById(Long id) {
        return handoverRecordRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Animal handover record", id));
    }

    /**
     * The preparation date is generated by the server. If the record is
     * created already confirmed, the confirmation date is the same server time.
     */
    @Transactional
    public AnimalHandoverRecord create(Long applicationId, String status) {
        AdoptionApplication application = getApplication(applicationId);
        String resolvedStatus = StringUtils.hasText(status) ? status : DEFAULT_STATUS;
        LocalDateTime now = LocalDateTime.now();

        AnimalHandoverRecord record = AnimalHandoverRecord.builder()
                .application(application)
                .preparationDate(now)
                .confirmationDate(isConfirmed(resolvedStatus) ? now : null)
                .status(resolvedStatus)
                .build();
        return handoverRecordRepository.save(record);
    }

    /**
     * Confirmation time is never accepted from the client: it is set by the
     * server when the record becomes CONFIRMED and cleared otherwise.
     */
    @Transactional
    public AnimalHandoverRecord update(Long id, Long applicationId, String status) {
        AnimalHandoverRecord record = findById(id);

        if (applicationId != null) {
            record.setApplication(getApplication(applicationId));
        }
        if (StringUtils.hasText(status)) {
            boolean wasConfirmed = isConfirmed(record.getStatus());
            record.setStatus(status);

            if (isConfirmed(status)) {
                if (!wasConfirmed || record.getConfirmationDate() == null) {
                    record.setConfirmationDate(LocalDateTime.now());
                }
            } else {
                record.setConfirmationDate(null);
            }
        }
        return handoverRecordRepository.save(record);
    }

    @Transactional
    public void delete(Long id) {
        findById(id);
        handoverRecordRepository.deleteById(id);
    }

    private AdoptionApplication getApplication(Long applicationId) {
        return adoptionApplicationRepository.findById(applicationId)
                .orElseThrow(() -> new ResourceNotFoundException("Adoption application", applicationId));
    }

    private boolean isConfirmed(String status) {
        return CONFIRMED_STATUS.equalsIgnoreCase(status);
    }
}
